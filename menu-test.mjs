
// Menu button check: SHOTS=<dir> URL=<base> W=390 node menu-test.mjs (headless chrome on :9333)
const S = process.env.SHOTS, BASE = process.env.URL || 'http://127.0.0.1:8767/', W = +process.env.W || 390;
const tabs = await (await fetch('http://127.0.0.1:9333/json')).json();
const ws = new WebSocket(tabs.find(t => t.type === 'page').webSocketDebuggerUrl);
await new Promise(r => ws.onopen = r);
let id = 0; const pend = {};
ws.onmessage = m => { const x = JSON.parse(m.data); if (pend[x.id]) { pend[x.id](x.result); delete pend[x.id]; } };
const cdp = (method, params = {}) => new Promise(r => { pend[++id] = r; ws.send(JSON.stringify({ id, method, params })); });
const ev = async e => (await cdp('Runtime.evaluate', { expression: e, returnByValue: true })).result.value;
const sleep = ms => new Promise(r => setTimeout(r, ms));
const shot = async n => { const r = await cdp('Page.captureScreenshot'); (await import('fs')).writeFileSync(`${S}/${n}.png`, Buffer.from(r.data, 'base64')); };
const ok = (c, m) => { console.log((c ? 'PASS ' : 'FAIL ') + m); if (!c) process.exitCode = 1; };
const tap = async sel => { const r = await ev(`(()=>{const b=document.querySelector('${sel}').getBoundingClientRect();return [b.x+b.width/2,b.y+b.height/2]})()`);
  for (const type of ['mousePressed', 'mouseReleased']) await cdp('Input.dispatchMouseEvent', { type, x: r[0], y: r[1], button: 'left', clickCount: 1 }); };
await cdp('Network.enable'); await cdp('Network.setCacheDisabled', { cacheDisabled: true });
await cdp('Emulation.setDeviceMetricsOverride', { width: W, height: 844, deviceScaleFactor: 2, mobile: W < 700 });
await cdp('Page.navigate', { url: BASE + 'index.html' }); await sleep(3500);
await ev(`document.querySelector('.pop-d[open]')?.close()`);
const root = W < 700 ? '.v-mob' : '.v-desk';
ok(await ev(`!document.querySelector('${root} header .btn.sun')`), 'no reserve button in header');
const a1 = await ev(`getComputedStyle(document.querySelector('${root} header .mbtn-ring')).rotate`); await sleep(1000);
const a2 = await ev(`getComputedStyle(document.querySelector('${root} header .mbtn-ring')).rotate`);
ok(a1 !== a2, `petal ring turns (${a1} -> ${a2})`);
await shot(`menu-btn-${W}`);
await tap(`${root} header .mbtn`); await sleep(250); await shot(`menu-mid-${W}`);
ok(await ev(`!document.querySelector('${root} .menu-wrap').hidden`), 'menu opens');
await sleep(1100); await shot(`menu-open-${W}`);
const xb = await ev(`(()=>{const a=document.querySelector('${root} .menu-wrap .mbtn.x').getBoundingClientRect();return [Math.round(a.x),Math.round(a.y)]})()`);
ok(xb[0] > 0, 'close button visible ' + JSON.stringify(xb));
await tap(`${root} .menu-wrap .mbtn.x`); await sleep(150);
ok(await ev(`document.querySelector('${root} .menu-wrap').classList.contains('closing')`), 'closing animation');
await sleep(600);
ok(await ev(`document.querySelector('${root} .menu-wrap').hidden && document.body.style.overflow === ''`), 'menu closed, scroll restored');
await tap(`${root} header .mbtn`); await sleep(1000);
await tap(`${root} .menu-wrap nav a[href^="#kaart"]`); await sleep(1200);
ok(await ev(`document.querySelector('${root} .menu-wrap').hidden && scrollY > 500`), 'link closes menu and scrolls');
ok(await ev(`document.documentElement.scrollWidth <= innerWidth`), 'no overflow');
ws.close();
